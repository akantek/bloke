import sys

TILE_MAP = {
    # --- Background & Whitespace ---
    '.': 0x00,  # _blank_pattern
    ' ': 0x27,  # _space_pattern

    # --- Numbers (IDs $01 to $0A) ---
    '0': 0x01, '1': 0x02, '2': 0x03, '3': 0x04, '4': 0x05,
    '5': 0x06, '6': 0x07, '7': 0x08, '8': 0x09, '9': 0x0A,

    # --- Alphabet (IDs $0B to $24) ---
    'A': 0x0B, 'B': 0x0C, 'C': 0x0D, 'D': 0x0E,
    'E': 0x0F, 'F': 0x10, 'G': 0x11, 'H': 0x12,
    'I': 0x13, 'J': 0x14, 'K': 0x15, 'L': 0x16,
    'M': 0x17, 'N': 0x18, 'O': 0x19, 'P': 0x1A,
    'Q': 0x1B, 'R': 0x1C, 'S': 0x1D, 'T': 0x1E,
    'U': 0x1F, 'V': 0x20, 'W': 0x21, 'X': 0x22,
    'Y': 0x23, 'Z': 0x24,

    # --- Punctuation (IDs $25 to $26) ---
    '!': 0x25,  # _exclamation_pattern
    ';': 0x26,  # _semi_colon_pattern

    # --- Background Lines (IDs $28 to $2F) ---
    'a': 0x28,  # _background_line_a_pattern
    'b': 0x29,  # _background_line_b_pattern
    'c': 0x2A,  # _background_line_c_pattern
    'd': 0x2B,  # _background_line_d_pattern
    'e': 0x2C,  # _background_line_e_pattern
    'f': 0x2D,  # _background_line_f_pattern
    'g': 0x2E,  # _background_line_g_pattern
    'h': 0x2F,  # _background_line_h_pattern

    # --- Stars (ID $30) ---
    '*': 0x30,  # _star_0_pattern

    # --- Title Graphics (IDs $31 to $34) ---
    '/':  0x31,  # _title_diag_top_right_pattern
    '\\': 0x32,  # _title_diag_top_left_pattern
    ']':  0x33,  # _title_diag_bottom_right_pattern
    '=':  0x34,  # _title_line_pattern

    # --- Temporary Dash Alias (see note below) ---
    '-':  0x2C,  # Maps to _background_line_e_pattern (centered 1px line)
}


def parse_map(input_file, output_file, label_name):
    # Read the text file, ignoring empty lines
    with open(input_file, 'r') as f:
        lines = [line.strip('\n') for line in f if line.strip()]

    # Validate screen dimensions
    if len(lines) != 24:
        print(f"Warning: Expected 24 rows, found {len(lines)} in {input_file}")

    with open(output_file, 'w') as out:
        out.write("; =================================================================\n")
        out.write("; AUTOGENERATED FILE - DO NOT EDIT MANUALLY\n")
        out.write(f"; Generated from {input_file}\n")
        out.write("; =================================================================\n\n")

        out.write(f"{label_name}:\n")

        for row_idx, line in enumerate(lines):
            # Pad with blank tiles if the line is shorter than 32 chars
            line = line.ljust(32, '.')
            if len(line) > 32:
                print(f"Warning: Row {row_idx} is longer than 32 characters. Truncating.")
                line = line[:32]

            hex_values = []
            for col_idx, char in enumerate(line):
                if char not in TILE_MAP:
                    print(
                        f"Warning: Unknown char '{char}' at row {row_idx}, col {col_idx}. "
                        "Defaulting to $00."
                    )
                tile_id = TILE_MAP.get(char, 0x00)
                hex_values.append(f"${tile_id:02X}")

            # Write 32 bytes per row using defb
            out.write(f"  defb {', '.join(hex_values)}  ; Row {row_idx}\n")


if __name__ == "__main__":
    if len(sys.argv) == 4:
        parse_map(sys.argv[1], sys.argv[2], sys.argv[3])
    else:
        print("Usage: python3 map_parser.py <input.txt> <output.asm> <label_name>")

