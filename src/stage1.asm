;  Player starting position.
stage1_sprite0_attributes_data:
  ;  Y,   X,   Pat, Color
  db 138, 10,  4,   15       ; Pat = 0 (_bloke_right_0), Color = 15 (White)

; Stage 1 routine
stage1:
  ; SCREEN OFF
  call DISSCR

  di

  ; clear(SCREEN2)
  call clear_screen2

  ; Draw the stage 1 background
  ld hl, stage1_map          ; Point to the autogenerated map data
  ld de, $1800               ; VRAM address for SCREEN 2 Name Table
  ld bc, 768                 ; 32x24 map = 768 bytes
  call write_vram_large      ; Blast it to the VDP!

  ; Init sprites
  call init_sprite_attributes

  ; Init player sprite (sprite0_*)
  xor a
  ld (player_direction), a   ; 0 = Right facing base
  ld (player_anim_frame), a  ; 0 = Frame 0
  ld (player_anim_timer), a  ; 0 = Reset timer
  ld (sprite0_pat), a        ; Set Pattern ID to 0

  ; SCREEN ON
  call ENASCR

  ei

stage1_loop:
  call wait_vsync        ; Spin until vblank is fired
.stage1_vblank_trace_start:
  ; ==========================================================================
  ; Phase: Render
  ; ==========================================================================

  ; Update sprites immediately while the VDP is guaranteed to be blanking.
  ld a, INIT_NUM_SPRITES 
  call loadSpriteAttributes
.stage1_vblank_trace_end:
  ; ==========================================================================
  ; Phase: Input + Logic (where do things want to go?)
  ; ==========================================================================
  call update_player_movement
  call update_player_animation
  call update_npcs

  ; ==========================================================================
  ; Phase: Collision Detection & Physics (are they allowed to go there?))
  ; ==========================================================================
  call check_wall_collisions
  call check_sprite_collisions

  jp stage1_loop


; ==============================================================================
; Routine:      update_player_movement
; Description:  Scans the keyboard, updates sprite0 X/Y coordinates, sets the 
;               player_direction flag, and toggles the player_is_walking state.
;               Includes early-exit optimization if no keys are pressed.
;
; Inputs:       None
; Outputs:      Updates RAM: sprite0_x, sprite0_y, player_direction, 
;               player_is_walking
; Destroys:     AF, C (from scan_keypad), E, HL
; ==============================================================================
update_player_movement:
  ; 1. Reset walking flag at the start of every frame
  xor a
  ld (player_is_walking), a

  ; 2. Read Keyboard
  call scan_keypad
  cp $F7                     ; Idle state for our specific matrix read
  ret z                      ; EARLY EXIT: No keys pressed, just return!

  ld e, a                    ; Backup matrix state into E

  ; --- RIGHT CHECK ---
  bit KEY_RIGHT_BIT, e
  jr nz, .not_right_key
  
  ld hl, sprite0_x
  inc (hl)                   ; Move Right
  ld a, PLAYER_DIRECTION_RIGHT
  ld (player_direction), a   ; Face Right
  ld a, 1
  ld (player_is_walking), a  ; Flag that we walked
  jr .not_left_key           ; Skip left check if moving right!

.not_right_key:
  ; --- LEFT CHECK ---
  bit KEY_LEFT_BIT, e
  jr nz, .not_left_key
  
  ld hl, sprite0_x
  dec (hl)                   ; Move Left
  ld a, PLAYER_DIRECTION_LEFT
  ld (player_direction), a   ; Face Left
  ld a, 1
  ld (player_is_walking), a  ; Flag that we walked

.not_left_key:
  ; --- UP CHECK ---
  bit KEY_UP_BIT, e
  jr nz, .not_up_key
  
  ld hl, sprite0_y
  dec (hl)                   ; Move Up
.not_up_key:
  ; --- DOWN CHECK ---
  bit KEY_DOWN_BIT, e
  jr nz, .not_down_key
  
  ld hl, sprite0_y
  inc (hl)                   ; Move Down
.not_down_key:  
  ret


; ==============================================================================
; Routine:      update_player_animation
; Description:  Reads the player_is_walking flag to determine if the player 
;               should be animated. Calculates the ping-pong walking animation 
;               frames (0->4->8->4 offsets) every 8 VBlanks. If stopped, snaps 
;               the sprite to the correct directional Idle Pattern.
;
; Inputs:       None (Reads RAM: player_is_walking, player_direction)
; Outputs:      Updates RAM: sprite0_pat, player_anim_timer, player_anim_frame
; Destroys:     AF, C, HL
; ==============================================================================
update_player_animation:
  ld a, (player_is_walking)
  or a                       
  jr z, .set_idle_state      ; If 0, skip animation and jump to Idle logic

  ; ==========================================
  ; WALKING ANIMATION (Ping-Pong: 0, 4, 8, 4)
  ; ==========================================
  ld hl, player_anim_timer
  inc (hl)
  ld a, (hl)
  cp 8                       ; Have 8 frames passed?
  jr c, .apply_anim          ; If timer < 8, keep current frame

  ; Timer reached 8: Reset timer and advance phase
  xor a
  ld (hl), a                 ; Reset timer to 0

  ld hl, player_anim_frame
  inc (hl)                   ; Next phase (0, 1, 2, or 3)
  ld a, (hl)
  and 3                      ; Mask to keep it wrapping between 0 and 3
  ld (hl), a

.apply_anim:
  ; Convert Phase (0-3) to Pattern Offset (0, 4, 8, 4)
  ld a, (player_anim_frame)
  ld c, 4                    ; Pre-load C with 4 (Offset for Phase 3)
  cp 3                       
  jr z, .got_offset          ; If Phase is 3, skip math! C is already 4.
  
  ; For Phase 0, 1, and 2: Multiply by 4
  add a, a
  add a, a                   ; A is now 0, 4, or 8
  ld c, a                    ; Store calculated offset in C

.got_offset:
  ; Calculate Final Pattern: Base Pattern + Offset (C)
  ld a, (player_direction)
  cp PLAYER_DIRECTION_RIGHT
  jr z, .base_right

  ; Must be Left
  ld a, 0                    ; Left Base Pattern = 0
  jr .calc_pat
  
.base_right:
  ld a, 12                   ; Right Base Pattern = 12

.calc_pat:
  add a, c                   ; A = Base (0 or 12) + Offset (0, 4, or 8)
  ld (sprite0_pat), a        
  ret                        ; Done with animation, return to main loop

  ; ==========================================
  ; IDLE STATE (Runs if player stopped)
  ; ==========================================
.set_idle_state:
  ; Reset animation state so the ping-pong sequence restarts properly next time
  xor a
  ld (player_anim_timer), a
  ld (player_anim_frame), a  

  ld a, (player_direction)
  cp PLAYER_DIRECTION_RIGHT  
  jr nz, .idle_left

  ; Snap to Right Idle
  ld a, 16                   ; Right Idle Pattern = 16
  ld (sprite0_pat), a
  ret

.idle_left:
  ; Snap to Left Idle
  ld a, 4                    ; Left Idle Pattern = 4
  ld (sprite0_pat), a
  ret


